std::string generateGameBuildConfigHeader(const ProjectConfig&   cfg,
                                          const ProjectSettings* settings,
                                          const char*            buildProfile,
                                          const std::uint8_t*    keyMask)
{
    std::uint8_t mask[32] = {}, masked[32] = {};
    if (cfg.encrypted)
    {
        if (keyMask) std::memcpy(mask, keyMask, 32);
        else if (!Hpak::randomBytes(mask, 32)) return {};
        for (int i = 0; i < 32; ++i) masked[i] = cfg.encKey[i] ^ mask[i];
    }

    // The JSON tails in the shape the hcfg writer emits; "" for a default, so a
    // project that never touched them reads as such.
    std::string layers, buses, project;
    if (!cfg.collisionLayers.isDefault())
    {
        nlohmann::json j = nlohmann::json::object();
        cfg.collisionLayers.toJson(j);
        layers = j.dump(-1, ' ', /*ensure_ascii=*/true);
    }
    if (!cfg.audioBuses.isDefault())
    {
        nlohmann::json j = nlohmann::json::object();
        cfg.audioBuses.toJson(j);
        buses = j.dump(-1, ' ', /*ensure_ascii=*/true);
    }
    if (settings && !settings->isDefault())
    {
        nlohmann::json j;
        settings->toJson(j);
        project = j.dump(2, ' ', /*ensure_ascii=*/true);
    }

    std::ostringstream h;
    h << "// HEGameBuildConfig.h, generated by the Horizon Engine exporter\n"
         "// (HE::generateGameBuildConfigHeader, src/HE_Core/src/Hpak/GameBuildConfig.cpp).\n"
         "// Do not edit: export again instead.\n"
         "//\n"
         "// Compiled into HorizonGame with -DHE_GAME_BUILD_CONFIG=<this file>; the game then\n"
         "// reads no project.hcfg and no Config/ProjectSettings.json. It carries the pak key\n"
         "// (masked, not encrypted): treat it like the game executable and do not ship or\n"
         "// commit it.\n"
         "#pragma once\n"
         "#include <Hpak/GameBuildConfig.h>\n"
         "\n"
         "static_assert(HE::kGameBuildConfigFormat == " << kGameBuildConfigFormat << ",\n"
         "              \"HEGameBuildConfig.h was generated for another engine version: export again\");\n"
         "\n"
         "namespace HE::GameBuild\n"
         "{\n"
         "inline constexpr HE::GameBuildConfig kConfig = {\n";
    h << "    .format                = " << kGameBuildConfigFormat << ",\n";
    h << "    .buildProfile          = " << cppString(buildProfile ? buildProfile : "") << ",\n";
    h << "\n";
    h << "    .projectName           = " << cppString(cfg.projectName) << ",\n";
    h << "    .hpakFilename          = " << cppString(cfg.hpakFilename) << ",\n";
    h << "    .mainSceneName         = " << cppString(cfg.mainSceneName) << ",\n";
    h << "    .defaultSaveTemplate   = " << cppString(cfg.defaultSaveTemplate) << ",\n";
    h << "    .theme                 = " << cppString(cfg.theme) << ",\n";
    h << "    .themeMode             = " << cppString(cfg.themeMode) << ",\n";
    h << "    .bundleId              = " << cppString(cfg.bundleId) << ",\n";
    h << "\n";
    h << "    .enableModSupport      = " << boolText(cfg.enableModSupport) << ",\n";
    h << "    .devTools              = " << boolText(cfg.devTools) << ",\n";
    h << "    .encrypted             = " << boolText(cfg.encrypted) << ",\n";
    h << "    .hasPackedScene        = " << boolText(cfg.hasPackedScene) << ",\n";
    h << "    .horizonCodeCompiled   = " << boolText(cfg.horizonCodeCompiled) << ",\n";
    h << "    .appMode               = " << boolText(cfg.appMode) << ",\n";
    h << "    .advancedShaderEffects = " << boolText(cfg.advancedShaderEffects) << ",\n";
    h << "    .allowFiles            = " << boolText(cfg.allowFiles) << ",\n";
    h << "    .allowProcesses        = " << boolText(cfg.allowProcesses) << ",\n";
    h << "    .allowNetwork          = " << boolText(cfg.allowNetwork) << ",\n";
    h << "    .fontScripts           = " << cfg.fontScripts << "u,\n";
    h << "    .fontWeightBold        = " << boolText(cfg.fontWeightBold) << ",\n";
    h << "\n";
    h << "    .startupSceneUuid      = " << byteList(cfg.startupSceneUuid, 16) << ",\n";
    h << "    .pakKeyMasked          = " << byteList(masked, 32) << ",\n";
    h << "    .pakKeyMask            = " << byteList(mask, 32) << ",\n";
    h << "\n";
    h << "    .collisionLayersJson   = " << cppRawString(layers) << ",\n";
    h << "    .audioBusesJson        = " << cppRawString(buses) << ",\n";
    h << "    .projectSettingsJson   = " << cppRawString(project) << ",\n";
    h << "};\n"
         "} // namespace HE::GameBuild\n";
    return h.str();
}

bool writeGameBuildConfigHeader(const std::filesystem::path& file,
                                const ProjectConfig&         cfg,
                                const ProjectSettings*       settings,
                                const char*                  buildProfile,
                                const std::uint8_t*          keyMask)
{
    const std::string text = generateGameBuildConfigHeader(cfg, settings, buildProfile, keyMask);
    if (text.empty()) return false;
    std::error_code ec;
    if (file.has_parent_path()) std::filesystem::create_directories(file.parent_path(), ec);
    std::ofstream f(file, std::ios::binary | std::ios::trunc);
    if (!f) return false;
    f.write(text.data(), static_cast<std::streamsize>(text.size()));
    return f.good();
}

bool readGameBuildConfigPakKey(const std::filesystem::path& file, std::uint8_t outKey[32])
{
    std::ifstream f(file, std::ios::binary);
    if (!f) return false;
    const std::string text((std::istreambuf_iterator<char>(f)), std::istreambuf_iterator<char>());
    if (text.find(".encrypted             = true") == std::string::npos) return false;
    std::uint8_t masked[32], mask[32];
    if (!parseByteList(text, "pakKeyMasked", masked) || !parseByteList(text, "pakKeyMask", mask))
        return false;
    for (int i = 0; i < 32; ++i) outKey[i] = masked[i] ^ mask[i];
    return true;
}

void projectConfigFromBuildConfig(const GameBuildConfig& c, ProjectConfig& out)
{
    out = ProjectConfig{};
    out.projectName         = c.projectName ? c.projectName : "";
    out.hpakFilename        = c.hpakFilename ? c.hpakFilename : "";
    out.mainSceneName       = c.mainSceneName ? c.mainSceneName : "";
    out.defaultSaveTemplate = c.defaultSaveTemplate ? c.defaultSaveTemplate : "";
    out.theme               = c.theme ? c.theme : "";
    out.themeMode           = c.themeMode ? c.themeMode : "";
    out.bundleId            = c.bundleId ? c.bundleId : "";

    out.enableModSupport      = c.enableModSupport;
    out.devTools              = c.devTools;
    out.encrypted             = c.encrypted;
    out.hasPackedScene        = c.hasPackedScene;
    out.horizonCodeCompiled   = c.horizonCodeCompiled;
    out.appMode               = c.appMode;
    out.advancedShaderEffects = c.advancedShaderEffects;
    out.allowFiles            = c.allowFiles;
    out.allowProcesses        = c.allowProcesses;
    out.allowNetwork          = c.allowNetwork;
    out.fontScripts           = c.fontScripts;
    out.fontWeightBold        = c.fontWeightBold;

    std::memcpy(out.startupSceneUuid, c.startupSceneUuid, 16);
    if (c.encrypted)
        for (int i = 0; i < 32; ++i) out.encKey[i] = c.pakKeyMasked[i] ^ c.pakKeyMask[i];

    // Same bargain as the hcfg reader: a tail that does not parse keeps the
    // default rather than costing the game its pak and scene.
    if (c.collisionLayersJson && *c.collisionLayersJson)
    {
        const nlohmann::json j = nlohmann::json::parse(c.collisionLayersJson, nullptr, false);
        if (!j.is_discarded()) out.collisionLayers.fromJson(j);
    }
    if (c.audioBusesJson && *c.audioBusesJson)
    {
        const nlohmann::json j = nlohmann::json::parse(c.audioBusesJson, nullptr, false);
        if (!j.is_discarded()) out.audioBuses.fromJson(j);
    }
}

const char* projectConfigSourceName(ProjectConfigSource s)
{
    switch (s)
    {
    case ProjectConfigSource::Compiled:    return "compiled in (HEGameBuildConfig.h)";
    case ProjectConfigSource::ProjectFile: return "project.hcfg";
    case ProjectConfigSource::None:        break;
    }
    return "none";
}

ProjectConfigSource resolveProjectConfig(const GameBuildConfig*       compiled,
                                         const std::filesystem::path& dir,
                                         ProjectConfig&               out)
{
    if (compiled)
    {
        projectConfigFromBuildConfig(*compiled, out);
        return ProjectConfigSource::Compiled;
    }
    return ProjectConfigLoader::load(dir, out) ? ProjectConfigSource::ProjectFile
                                               : ProjectConfigSource::None;
}

bool resolveProjectSettings(const GameBuildConfig*       compiled,
                            const std::filesystem::path& dir,
                            ProjectSettings&             out)
{
    if (!compiled) return loadProjectSettings(dir, out);
    out = ProjectSettings{};
    if (!compiled->projectSettingsJson || !*compiled->projectSettingsJson) return true;
    const nlohmann::json j = nlohmann::json::parse(compiled->projectSettingsJson, nullptr, false);
    if (j.is_discarded() || !j.is_object()) return false;
    out.fromJson(j);
    return true;
}

const char* pakKeySourceName(PakKeySource s)
{
    switch (s)
    {
    case PakKeySource::Compiled:      return "HEGameBuildConfig.h (compiled in)";
    case PakKeySource::EmbeddedBlock: return "executable key block";
    case PakKeySource::ProjectFile:   return "project.hcfg";
    case PakKeySource::None:          break;
    }
    return "none";
}

PakKeySource selectPakKey(ProjectConfigSource  source,
                          const ProjectConfig& cfg,
                          const std::uint8_t*  embeddedKey,
                          const std::uint8_t*& outKey)
{
    outKey = nullptr;
    if (source == ProjectConfigSource::Compiled)
    {
        if (!cfg.encrypted) return PakKeySource::None;
        outKey = cfg.encKey;
        return PakKeySource::Compiled;
    }
    // The prebuilt runtime's order, unchanged: the patched block, then the hcfg.
    if (embeddedKey)
    {
        outKey = embeddedKey;
        return PakKeySource::EmbeddedBlock;
    }
    if (source == ProjectConfigSource::ProjectFile && cfg.encrypted)
    {
        outKey = cfg.encKey;
        return PakKeySource::ProjectFile;
    }
    return PakKeySource::None;
}

