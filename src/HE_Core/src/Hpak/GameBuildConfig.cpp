// A C++ string literal for `s`. Printable ASCII stays as it is so the header
// reads like the project; everything else is a three-digit octal escape, which
// (unlike \x) cannot swallow the character after it, and keeps UTF-8 names
// byte-exact on compilers that do not read the source as UTF-8 (MSVC without
// /utf-8).
std::string cppString(const std::string& s)
{
    std::string out = "\"";
    for (const unsigned char c : s)
    {
        if (c == '"' || c == '\\')       { out += '\\'; out += static_cast<char>(c); }
        else if (c >= 0x20 && c < 0x7f)  out += static_cast<char>(c);
        else
        {
            char buf[8];
            std::snprintf(buf, sizeof buf, "\\%03o", c);
            out += buf;
        }
    }
    return out + "\"";
}

// A raw string literal for a JSON payload (dumped ASCII-only, so the raw form
// holds no byte a compiler could re-encode). The delimiter grows until the
// payload cannot close it early.
std::string cppRawString(const std::string& s)
{
    if (s.empty()) return "\"\"";
    std::string delim = "hecfg";
    while (s.find(")" + delim + "\"") != std::string::npos) delim += '_';
    return "R\"" + delim + "(" + s + ")" + delim + "\"";
}

std::string byteList(const std::uint8_t* b, size_t n)
{
    std::string out = "{ ";
    for (size_t i = 0; i < n; ++i)
    {
        char buf[8];
        std::snprintf(buf, sizeof buf, "0x%02x", b[i]);
        out += buf;
        if (i + 1 < n) out += (i % 16 == 15) ? ",\n                              " : ", ";
    }
    return out + " }";
}

const char* boolText(bool b) { return b ? "true" : "false"; }

// The 32 hex bytes after `.<field>` in a header this file generated.
bool parseByteList(const std::string& text, const char* field, std::uint8_t out[32])
{
    // The trailing blank keeps ".pakKeyMask" from matching ".pakKeyMasked".
    const std::string tag = std::string(".") + field + " ";
    size_t pos = text.find(tag);
    if (pos == std::string::npos) return false;
    pos = text.find('{', pos);
    const size_t end = text.find('}', pos);
    if (pos == std::string::npos || end == std::string::npos) return false;
    std::istringstream in(text.substr(pos + 1, end - pos - 1));
    std::string tok;
    int n = 0;
    while (std::getline(in, tok, ','))
    {
        if (n >= 32) return false;
        unsigned v = 0;
        if (std::sscanf(tok.c_str(), " 0x%x", &v) != 1 || v > 0xff) return false;
        out[n++] = static_cast<std::uint8_t>(v);
    }
    return n == 32;
}

