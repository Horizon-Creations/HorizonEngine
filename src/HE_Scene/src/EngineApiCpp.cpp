#include "HorizonScene/EngineApiCpp.h"
#include <string>
#include <vector>

namespace HE::api::cpp {

using P = PinType;

const char* pinTypeName(PinType t)
{
    switch (t)
    {
        case P::Exec:      return "Exec";
        case P::Float:     return "Float";
        case P::Bool:      return "Bool";
        case P::Int:       return "Int";
        case P::String:    return "String";
        case P::Vec2:      return "Vec2";
        case P::Color:     return "Color";
        case P::Ref:       return "Ref";
        case P::Transform: return "Transform";
        case P::Enum:      return "Enum";
        case P::Struct:    return "Struct";
        case P::Vec3:      return "Vec3";
        case P::Vec4:      return "Vec4";
        case P::Double:    return "Double";
    }
    return "Exec";
}

std::string valueType(PinType t, bool isArray)
{
    const char* scalar = "int";
    switch (t)
    {
        case P::Float:     scalar = "float"; break;
        case P::Double:    scalar = "double"; break;
        case P::Bool:      scalar = "bool"; break;
        case P::Int:
        case P::Enum:      scalar = "int"; break;
        case P::String:    scalar = "std::string"; break;
        case P::Vec2:      scalar = "glm::vec2"; break;
        case P::Vec3:      scalar = "glm::vec3"; break;
        case P::Vec4:      scalar = "::hc::Vec4"; break;
        case P::Color:     scalar = "glm::vec4"; break;
        case P::Ref:       scalar = "uint32_t"; break;
        case P::Transform: scalar = "::hc::Transform"; break;
        case P::Struct:    scalar = "HorizonCode::Value"; break;
        case P::Exec:      scalar = "void"; break;
    }
    return isArray ? "std::vector<" + std::string(scalar) + ">" : std::string(scalar);
}

std::string callExpr(const ApiFn& fn, const std::string& ctx,
                     const std::vector<std::string>& args)
{
    if (fn.cppForm == CppForm::Thunk || args.size() != fn.params.size()) return {};
    std::string s = std::string(fn.cppCall) + "(";
    bool first = true;
    if (fn.cppForm == CppForm::Ctx) { s += ctx; first = false; }
    for (size_t i = 0; i < args.size(); ++i)
    {
        if (!first) s += ", ";
        first = false;
        const ApiParam& p = fn.params[i];
        // The registry's thunk substitutes the caller for a 0 here (EngineApi.cpp,
        // the selfDefault post-passes); a direct call asks the same function.
        if (p.selfDefault && p.type == P::Ref)
            s += "HE::api::widgetOrSelf(" + ctx + ", " + args[i] + ", \"" + fn.id + "\")";
        else if (p.selfDefault)
            s += "HE::api::entityOrSelf(" + ctx + ", " + args[i] + ", \"" + fn.id + "\")";
        else
            s += args[i];
    }
    return s + ")";
}

const char* hookArgType(PinType arg)
{
    return arg == P::String ? "const std::string&"
         : arg == P::Float  ? "float"
         : arg == P::Bool   ? "bool"
         : arg == P::Vec2   ? "const glm::vec2&"
         : arg == P::Color  ? "const glm::vec4&" : "int";
}

namespace {

std::string identOf(const char* id)
{
    std::string s = id;
    for (char& ch : s)
        if (ch == '.') ch = '_';
    return s;
}

} // namespace

std::string hookParams(const HorizonCode::EngineEventDesc& e, bool argUsed)
{
    std::string p;
    if (e.elem) p = "int elem";
    if (e.arg != P::Exec)
    {
        if (!p.empty()) p += ", ";
        p += std::string(hookArgType(e.arg)) + (argUsed ? " arg" : "");
    }
    return p;
}

std::string directCallsSource()
{
    std::string s;
    s += "// Generated by `hc_codegen --api-direct` from HE::api::registry(). Do not edit:\n"
         "// he_tests regenerates it on every build, so a registry row whose cppCall,\n"
         "// cppForm or params do not match its C++ function stops the build here, at\n"
         "// the line that names it. See tests/test_engine_api_direct.cpp.\n"
         "#include <HorizonEngine/HorizonEngineApi.h>\n"
         "#include \"engine_api_direct.h\"\n"
         "\n"
         "namespace he_api_direct {\n"
         "namespace {\n"
         "\n"
         "using P = HorizonCode::PinType;\n"
         "\n"
         "// The argument as generated code holds it: a variable of the pin's C++ type.\n"
         "template <P T> HE::api::pin::type<T> arg(const VV& a, size_t k)\n"
         "{\n"
         "    if constexpr (T == P::Struct) return k < a.size() ? a[k] : Value{};\n"
         "    else return ::hc::fromValue<HE::api::pin::type<T>>(a, k);\n"
         "}\n"
         "template <P T> std::vector<HE::api::pin::type<T>> args(const VV& a, size_t k)\n"
         "{ return ::hc::fromValueArray<HE::api::pin::type<T>>(a, k); }\n"
         "\n"
         "// The answer in the pin's shape, boxed the way generated code boxes a value.\n"
         "template <P T, typename X> Value box(const X& x)\n"
         "{\n"
         "    if constexpr (T == P::Struct) return x;\n"
         "    else return ::hc::toValue(HE::api::pin::toPin<T>(x));\n"
         "}\n"
         "template <P T, typename X> Value boxArray(const std::vector<X>& x)\n"
         "{ return ::hc::toValue(HE::api::pin::toPinArray<T>(x)); }\n"
         "\n";

    auto boxed = [](const ApiParam& r, const std::string& expr)
    {
        return std::string(r.isArray ? "boxArray<P::" : "box<P::") + pinTypeName(r.type) +
               ">(" + expr + ")";
    };

    std::vector<std::string> names;
    for (const ApiFn& fn : registry())
    {
        if (fn.cppForm == CppForm::Thunk) continue;
        const std::string name = identOf(fn.id);
        names.push_back(name);

        std::vector<std::string> a;
        for (size_t i = 0; i < fn.params.size(); ++i)
        {
            const ApiParam& p = fn.params[i];
            a.push_back(std::string(p.isArray ? "args<P::" : "arg<P::") + pinTypeName(p.type) +
                        ">(a, " + std::to_string(i) + ")");
        }
        const std::string call = callExpr(fn, "ctx", a);

        s += "// " + std::string(fn.id) + " (" + (fn.displayName ? fn.displayName : fn.id) + ")\n";
        s += "VV " + name + "(HE::api::Ctx& ctx, const VV& a)\n{\n";
        if (fn.params.empty()) s += "    (void)a;\n";
        if (fn.results.empty())
        {
            s += "    " + call + ";\n    return {};\n";
        }
        else if (fn.results.size() == 1)
        {
            s += "    return { " + boxed(fn.results[0], call) + " };\n";
        }
        else
        {
            // A struct whose members are the results in order: the names are
            // the result pins', which is what generated code would call them.
            std::string bind, ret;
            for (size_t i = 0; i < fn.results.size(); ++i)
            {
                const std::string n = std::string(fn.results[i].name) + "_";
                bind += (i ? ", " : "") + n;
                ret  += (i ? ", " : "") + boxed(fn.results[i], n);
            }
            s += "    auto [" + bind + "] = " + call + ";\n";
            s += "    return { " + ret + " };\n";
        }
        s += "}\n\n";
    }

    // Every engine event, overridden with the parameter list the HorizonCode
    // emitter writes for it: `override` refuses to compile when the hook in
    // CompiledInstance does not have exactly that signature.
    s += "// The engine's own events (HorizonCode::engineEvents()), as hooks.\n"
         "struct EngineEventHooks : HorizonCode::CompiledInstance\n{\n";
    for (const HorizonCode::EngineEventDesc& e : HorizonCode::engineEvents())
        s += "    void " + std::string(e.hook) + "(" + hookParams(e, false) + ") override {}\n";
    s += "};\n\n";

    s += "} // namespace\n\n"
         "const std::vector<Row>& rows()\n{\n"
         "    static const std::vector<Row> t = {\n";
    size_t k = 0;
    for (const ApiFn& fn : registry())
    {
        if (fn.cppForm == CppForm::Thunk) continue;
        s += "        { \"" + std::string(fn.id) + "\", &" + names[k++] + " },\n";
    }
    s += "    };\n    return t;\n}\n\n"
         "size_t engineEventHookCount() { return " +
         std::to_string(HorizonCode::engineEvents().size()) + "; }\n\n"
         "} // namespace he_api_direct\n";
    return s;
}

} // namespace HE::api::cpp
